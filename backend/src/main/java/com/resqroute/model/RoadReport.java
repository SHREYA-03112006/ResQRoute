package com.resqroute.model;

import jakarta.persistence.*;
import jakarta.validation.constraints.*;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.CreationTimestamp;

import java.time.Instant;

/**
 * A structured road-condition report derived from a public source or the TinyFish API.
 *
 * <p>Each report goes through validation → normalisation → road-matching → confidence scoring
 * before being accepted into the road graph.
 *
 * <p>The {@code dataMode} field distinguishes live TinyFish-retrieved data from
 * sample/mock data used during development. Never present sample data as live data.
 */
@Entity
@Table(name = "road_reports")
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class RoadReport {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /** Raw road or bridge name as extracted from the source. */
    @NotBlank
    @Column(nullable = false)
    private String reportedRoadName;

    /** Normalised name after cleaning (upper-case, stripped prefixes, etc.). */
    private String normalisedRoadName;

    /** Reported condition (OPEN / FLOODED / BLOCKED / UNCERTAIN). */
    @NotNull
    @Enumerated(EnumType.STRING)
    private RoadStatus reportedStatus;

    /** Free-text location description from the source. */
    private String locationDescription;

    /** Approximate latitude, if extractable from the source. */
    private Double latitude;

    /** Approximate longitude, if extractable from the source. */
    private Double longitude;

    /** Human-readable name of the news/advisory source. */
    private String sourceName;

    /** URL of the source article or advisory page. */
    @Column(length = 2048)
    private String sourceUrl;

    /** When the event was observed or the article was published (UTC), if available. */
    private Instant observedAt;

    /** When this record was retrieved from the source. */
    @CreationTimestamp
    @Column(updatable = false)
    private Instant retrievedAt;

    /**
     * Confidence score in [0.0, 1.0].
     * Computed from source type, recency, agreement and match quality.
     */
    @DecimalMin("0.0")
    @DecimalMax("1.0")
    @Builder.Default
    private Double confidenceScore = 0.0;

    /**
     * Road-match status:
     * UNMATCHED — no OSM edge found yet.
     * MATCHED    — linked to one or more OSM edges.
     * WEAK_MATCH — match found but spatial or name similarity is low (flags for review).
     * CONFLICT   — contradicts another recent report on the same segment.
     */
    @Builder.Default
    private String matchStatus = "UNMATCHED";

    /** ID of the matched OSM edge (graph edge), if available. */
    private Long matchedEdgeId;

    /**
     * Data origin mode.
     * LIVE   — data retrieved from TinyFish or a live source.
     * SAMPLE — pre-loaded test data (clearly labelled in the UI).
     * MOCK   — generated by the mock-data service.
     */
    @Builder.Default
    private String dataMode = "SAMPLE";

    /** Whether this report has been flagged for dispatcher review. */
    @Builder.Default
    private Boolean flaggedForReview = false;

    /** Optional dispatcher notes added during review. */
    @Column(columnDefinition = "TEXT")
    private String reviewNotes;
}
